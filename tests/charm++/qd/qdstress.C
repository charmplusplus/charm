// Quiescence detection (QD) correctness under stress.
//
// Every phase knows exactly how much work it must do (messages delivered,
// elements constructed or destroyed, bytes received). The driver, a [threaded]
// entry of the mainchare, starts the work and waits for quiescence, then sums
// the per-PE work counters (group Stats) in a reduction. A count short of the
// expected one means QD fired before the work was done:
//   CkAbort("qdstress phase X round R (QD by K): QD fired with N of M ...").
// It then waits for quiescence a second time and counts again; any counter that
// moved means work arrived after quiescence was reported.
//
// The driver waits for quiescence in three ways, rotating per round: CkWaitQD(),
// CkStartQD(CkCallbackResumeThread()), and CkStartQD with a callback to an entry
// of the mainchare. No work is generated by timers (QD does not count them).
//
// Phases (-phase NAME[,NAME...], default all; -rounds R, default 6):
//   migrate    4 elements per PE; message chains to random elements while the
//              elements migrateMe() to random PEs on every few deliveries (not
//              AtSync), so messages chase elements and are forwarded or buffered;
//              broadcasts reach migrating elements; arrivals must equal departures.
//   insert     elements are messaged from every PE before they exist; each is
//              inserted, on a PE other than its home for most indices, at the end
//              of a chain of group messages (no timer); each destroys itself
//              (ckDestroy) after its last expected message. Two arrays: one gets
//              doneInserting() after each round's insertions, the other only at
//              the end of the phase (an array still inserting blocks AtSync).
//   lb         AtSync load balancing (run with +balancer RotateLB; -rotate also
//              checks that every element moved). QD is started right after the
//              go() broadcast, so it must wait through the balancer, the resume,
//              a barrier reduction and the message chains the resume starts.
//              No message reaches an element between its AtSync and its
//              ResumeFromSync, and nothing calls migrateMe in that window (#4195).
//   zerocopy   nocopy entry parameters (CkSendBuffer), CkNcpyBuffer get and put,
//              each with 256-byte and 128 KB payloads; every byte is checked, and
//              every source and destination completion callback is counted.
//   groups     group chains through plain, [expedited] and [inline] entries; a
//              group broadcast from every PE; a group reduction to a broadcast
//              target; nodegroup chains through [exclusive] (checked for mutual
//              exclusion) and plain entries, nodegroup broadcasts and a reduction.
//   threads    a [threaded] group entry on every PE starts chains, then calls
//              CkStartQD (callback to its own branch) and CkWaitQD; all 2 * PEs
//              detections, plus the driver's, run at once. Each must fire, and
//              each PE's hop count when it fires must already be final.
//   completion the CompletionDetector library (-module completion): producers on
//              even PEs, consumers on odd PEs (PE 0 is both at 1 PE); items hop
//              between consumers before they are consumed. The finish callback
//              must come only after every item is consumed (checked without QD;
//              the second-quiescence check follows).
//   fakeqd     +qd N (fake QD) makes the runtime call the QD callback N seconds
//              after CkStartQD reaches PE 0 instead of detecting quiescence, so no
//              phase above can check the work at that time. Under +qd only this
//              phase runs: a counted chain reports its own end to the mainchare,
//              and the check is that the callback fires, no earlier than N
//              seconds after CkStartQD (it reaches _invokeQD in qd.C).

